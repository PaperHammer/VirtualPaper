#requires -Version 5.1
[CmdletBinding()]
param(
    [ValidateSet('All', 'UI', 'Core', 'Common', 'Installer', 'Manifest', 'Metadata')][string]$Target = 'All',
    [string]$SourceRoot,
    [string]$CatalogPath,
    [string]$ResourceMappingFile,
    [string]$MappingFile,
    [string]$XamlRoot,
    [string]$ManifestTemplate,
    [Parameter(Mandatory)][string]$OutputRoot,
    [switch]$Check
)
$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest
Add-Type -AssemblyName System.Xml.Linq
if (-not $SourceRoot) { $SourceRoot = Join-Path $PSScriptRoot 'Strings' }
if (-not $CatalogPath) { $CatalogPath = Join-Path $PSScriptRoot 'LanguageCatalog.json' }
if (-not $ResourceMappingFile) { $ResourceMappingFile = Join-Path $PSScriptRoot 'ResourceMappings.xml' }
if (-not $MappingFile) { $MappingFile = Join-Path $PSScriptRoot '../src/VirtualPaper.UIComponent/Localization/XamlResources.xml' }
if (-not $XamlRoot) { $XamlRoot = Join-Path $PSScriptRoot '../src' }
if (-not $ManifestTemplate) { $ManifestTemplate = Join-Path $PSScriptRoot '../Msix/Package.appxmanifest' }
. (Join-Path $PSScriptRoot 'LanguageCatalog.ps1')
$catalog = Get-LanguageCatalog $CatalogPath
$sourceRootPath = [IO.Path]::GetFullPath($SourceRoot).TrimEnd([IO.Path]::DirectorySeparatorChar)
$outputRootPath = [IO.Path]::GetFullPath($OutputRoot).TrimEnd([IO.Path]::DirectorySeparatorChar)
if ($sourceRootPath -ieq $outputRootPath -or $outputRootPath.StartsWith($sourceRootPath + [IO.Path]::DirectorySeparatorChar, [StringComparison]::OrdinalIgnoreCase)) {
    throw 'Generated resources must be outside the source Strings directory.'
}
foreach ($inputPath in @($sourceRootPath, $CatalogPath, $ResourceMappingFile, $MappingFile, $ManifestTemplate)) {
    if ([IO.Path]::GetFullPath($inputPath).StartsWith($outputRootPath + [IO.Path]::DirectorySeparatorChar, [StringComparison]::OrdinalIgnoreCase)) {
        throw 'Generated output must not contain source inputs.'
    }
}
$marker = 'Generated by localization/Generate-Resources.ps1. Do not edit.'
$expected = [Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
function Read-Xml([string]$Path) { return [Xml.Linq.XDocument]::Load([IO.Path]::GetFullPath($Path), [Xml.Linq.LoadOptions]::PreserveWhitespace) }
function Attribute($Element, [string]$Name) {
    $value = $Element.Attribute($Name)
    if ($null -eq $value) { return '' }
    return $value.Value
}
function Save-Generated([string]$Path, [string]$Content) {
    [void]$expected.Add([IO.Path]::GetFullPath($Path))
    $matches = (Test-Path -LiteralPath $Path) -and [IO.File]::ReadAllText($Path) -ceq $Content
    if ($Check) { if (-not $matches) { throw "Generated resources are missing or stale: $Path" } }
    elseif (-not $matches) {
        [void][IO.Directory]::CreateDirectory([IO.Path]::GetDirectoryName($Path))
        [IO.File]::WriteAllText($Path, $Content, [Text.UTF8Encoding]::new($false))
    }
}
function Save-Xml([string]$Path, $Document) {
    $Document.Root.AddBeforeSelf([Xml.Linq.XComment]::new(" $marker "))
    $settings = [Xml.XmlWriterSettings]::new()
    $settings.Encoding = [Text.UTF8Encoding]::new($false)
    $settings.NewLineChars = "`r`n"
    $settings.Indent = $true
    $stream = [IO.MemoryStream]::new()
    $writer = [Xml.XmlWriter]::Create($stream, $settings)
    try { $Document.Save($writer); $writer.Flush(); Save-Generated $Path ($settings.Encoding.GetString($stream.ToArray())) }
    finally { $writer.Dispose(); $stream.Dispose() }
}
function Add-String($Root, [string]$Name, $Value) {
    $entry = [Xml.Linq.XElement]::new([Xml.Linq.XName]::Get('data'))
    $entry.SetAttributeValue('name', $Name)
    $entry.SetAttributeValue([Xml.Linq.XNamespace]::Xml + 'space', 'preserve')
    $entry.Add([Xml.Linq.XElement]::new($Value))
    $Root.Add($entry)
}
function Format-Arguments([string]$Value) {
    return (@([regex]::Matches($Value, '(?<!\{)\{([0-9]+)(?:,[^}:]+)?(?::[^}]+)?\}(?!\})') |
        ForEach-Object { $_.Groups[1].Value } | Sort-Object -Unique) -join ',')
}

# Every advertised language is complete, including strings used only from code.
$documents = @{}; $strings = @{}
foreach ($language in $catalog.Languages) {
    $code = $language.Code
    $document = Read-Xml (Join-Path (Join-Path $sourceRootPath $code) 'Resources.resw')
    $entries = [Collections.Generic.Dictionary[string,Xml.Linq.XElement]]::new([StringComparer]::Ordinal)
    foreach ($entry in $document.Root.Elements('data')) {
        $name = Attribute $entry 'name'
        if ([string]::IsNullOrWhiteSpace($name) -or $entries.ContainsKey($name) -or $name.StartsWith('Ui_') -or $null -eq $entry.Element('value')) {
            throw "Missing/duplicate/generated resource key '$name' in $code."
        }
        $entries.Add($name, $entry.Element('value'))
    }
    $documents[$code] = $document; $strings[$code] = $entries
}
$baseline = $strings[$catalog.DefaultLanguage]
foreach ($code in $strings.Keys) {
    $entries = $strings[$code]
    if ($entries.Count -ne $baseline.Count) { throw "Source resource key counts differ: $code" }
    foreach ($key in $baseline.Keys) {
        if (-not $entries.ContainsKey($key) -or
            (-not [string]::IsNullOrWhiteSpace($baseline[$key].Value) -and [string]::IsNullOrWhiteSpace($entries[$key].Value)) -or
            (Format-Arguments $entries[$key].Value) -cne (Format-Arguments $baseline[$key].Value)) {
            throw "Missing translation or mismatched format arguments: $code/$key"
        }
    }
}
$sourceLocales = @([IO.Directory]::EnumerateDirectories($sourceRootPath) | Where-Object { Test-Path -LiteralPath (Join-Path $_ 'Resources.resw') } | ForEach-Object { [IO.Path]::GetFileName($_) })
if (@(Compare-Object ($catalog.Languages.Code | Sort-Object) ($sourceLocales | Sort-Object)).Count) { throw 'Source locales differ from the supported language catalog.' }
$resourceMappings = @((Read-Xml $ResourceMappingFile).Root.Elements('Resource'))
$mappingKeys = [Collections.Generic.HashSet[string]]::new([StringComparer]::Ordinal)
foreach ($mapping in $resourceMappings) {
    $kind = Attribute $mapping 'Target'; $name = Attribute $mapping 'Name'; $key = Attribute $mapping 'Source'
    if ($kind -cnotin @('Core', 'Common', 'Installer') -or $name -notmatch '^[A-Za-z_][A-Za-z0-9_]*$' -or
        -not $baseline.ContainsKey($key) -or -not $mappingKeys.Add("${kind}:$name")) { throw 'Invalid or duplicate runtime resource mapping.' }
}
foreach ($kind in @('Core', 'Common', 'Installer')) {
    if (@($resourceMappings | Where-Object { (Attribute $_ 'Target') -ceq $kind }).Count -eq 0) { throw "Runtime resource mappings are empty: $kind" }
}
# Keep the default first without relying on sort stability for the other locales.
$orderedLanguages = @($catalog.Languages | Where-Object { $_.Code -ceq $catalog.DefaultLanguage }) +
    @($catalog.Languages | Where-Object { $_.Code -cne $catalog.DefaultLanguage })
$targets = if ($Target -eq 'All') { @('UI', 'Core', 'Common', 'Installer', 'Manifest') } else { @($Target) }
foreach ($kind in $targets) {
    $root = if ($Target -eq 'All') { Join-Path $outputRootPath $kind } else { $outputRootPath }
    if ($kind -eq 'UI') {
        $mapping = [Collections.Generic.Dictionary[string,string]]::new([StringComparer]::Ordinal)
        foreach ($entry in (Read-Xml $MappingFile).Root.Elements('Resource')) {
            $name = Attribute $entry 'Name'; $key = Attribute $entry 'Source'
            if ($name -notmatch '^Ui_[^.]+\..+$' -or -not $baseline.ContainsKey($key) -or $mapping.ContainsKey($name)) { throw "Invalid/duplicate XAML resource mapping: $name" }
            $mapping.Add($name, $key)
        }
        if ($mapping.Count -eq 0) { throw 'XAML resource mappings are empty.' }
        $uids = [Collections.Generic.HashSet[string]]::new([StringComparer]::Ordinal)
        foreach ($name in $mapping.Keys) { [void]$uids.Add($name.Substring(0, $name.IndexOf('.'))) }
        $directories = [Collections.Generic.Stack[string]]::new(); $directories.Push([IO.Path]::GetFullPath($XamlRoot))
        while ($directories.Count -gt 0) {
            $directory = $directories.Pop()
            foreach ($child in [IO.Directory]::EnumerateDirectories($directory)) {
                if ([IO.Path]::GetFileName($child) -notin @('bin', 'obj', 'Plugins', '.git', 'node_modules')) { $directories.Push($child) }
            }
            foreach ($path in [IO.Directory]::EnumerateFiles($directory, '*.xaml')) {
                foreach ($attribute in (Read-Xml $path).Descendants().Attributes()) {
                    if ($attribute.Name.NamespaceName -eq 'using:WinUI3Localizer' -and $attribute.Name.LocalName -eq 'Uids.Uid' -and
                        -not $attribute.Value.StartsWith('{') -and -not $uids.Contains($attribute.Value)) { throw "Unmapped XAML UID: $($attribute.Value) ($path)" }
                }
            }
        }
        foreach ($language in $catalog.Languages) {
            $document = [Xml.Linq.XDocument]::new($documents[$language.Code])
            foreach ($name in @($mapping.Keys | Sort-Object)) { Add-String $document.Root $name $strings[$language.Code][$mapping[$name]] }
            Save-Xml (Join-Path (Join-Path $root $language.Code) 'Resources.resw') $document
        }
    }
    elseif ($kind -in @('Core', 'Common')) {
        foreach ($language in $catalog.Languages) {
            $document = [Xml.Linq.XDocument]::Parse('<root><resheader name="resmimetype"><value>text/microsoft-resx</value></resheader><resheader name="version"><value>2.0</value></resheader><resheader name="reader"><value>System.Resources.ResXResourceReader, System.Windows.Forms</value></resheader><resheader name="writer"><value>System.Resources.ResXResourceWriter, System.Windows.Forms</value></resheader></root>')
            foreach ($entry in $resourceMappings | Where-Object { (Attribute $_ 'Target') -ceq $kind }) {
                Add-String $document.Root (Attribute $entry 'Name') $strings[$language.Code][(Attribute $entry 'Source')]
            }
            $name = if ($kind -eq 'Core') { 'lang' } else { 'FileAccess' }
            if ($language.Code -cne $catalog.DefaultLanguage) { $name += '.' + $language.Code }
            Save-Xml (Join-Path $root "$name.resx") $document
        }
    }
    elseif ($kind -eq 'Installer') {
        $lines = @("; $marker", '[Languages]')
        foreach ($language in $orderedLanguages) {
            $line = 'Name: "{0}"; MessagesFile: "{1}";' -f $language.InstallerName, $language.InstallerMessagesFile
            $license = $language.PSObject.Properties['InstallerLicenseFile']
            if ($license) { $line += ' LicenseFile: "{0}";' -f $license.Value }
            $lines += $line
        }
        $lines += '', '[CustomMessages]'
        foreach ($language in $orderedLanguages) {
            $lines += "$($language.InstallerName).InitialApplicationLanguage=$($language.Code)"
            foreach ($entry in $resourceMappings | Where-Object { (Attribute $_ 'Target') -ceq 'Installer' }) {
                $text = $strings[$language.Code][(Attribute $entry 'Source')].Value
                if ($text -match '[\r\n]') { throw 'Installer messages must use Inno format tokens for line breaks.' }
                $lines += '{0}.{1}={2}' -f $language.InstallerName, (Attribute $entry 'Name'), $text
            }
        }
        Save-Generated (Join-Path $root 'Localization.iss') (($lines -join "`r`n") + "`r`n")
    }
    elseif ($kind -eq 'Manifest') {
        [xml]$document = Get-Content -LiteralPath $ManifestTemplate -Raw -Encoding UTF8
        $resources = $document.DocumentElement.SelectSingleNode("*[local-name()='Resources']")
        $resources.RemoveAll()
        foreach ($language in $orderedLanguages) {
            $entry = $document.CreateElement('Resource', $resources.NamespaceURI)
            $entry.SetAttribute('Language', $language.Code); [void]$resources.AppendChild($entry)
        }
        Save-Xml (Join-Path $root 'Package.appxmanifest') ([Xml.Linq.XDocument]::Parse($document.OuterXml))
    }
    $properties = [Xml.Linq.XDocument]::Parse('<Project><PropertyGroup/></Project>')
    foreach ($property in @{ DefaultLanguage = $catalog.DefaultLanguage; SupportedCultures = ($catalog.Languages.Code -join ';') }.GetEnumerator() | Sort-Object Key) {
        $properties.Root.Element('PropertyGroup').Add([Xml.Linq.XElement]::new([Xml.Linq.XName]::Get($property.Key), $property.Value))
    }
    Save-Xml (Join-Path $root 'Languages.props') $properties
    # Delete only obsolete files owned by this generator inside its output directory.
    if (Test-Path -LiteralPath $root) {
        foreach ($file in Get-ChildItem -LiteralPath $root -File -Recurse | Where-Object Extension -In @('.resw', '.resx', '.props', '.iss', '.appxmanifest')) {
            if (-not $expected.Contains($file.FullName) -and [IO.File]::ReadAllText($file.FullName).Contains($marker)) {
                if ($Check) { throw "Obsolete generated resource: $($file.FullName)" }
                [IO.File]::Delete($file.FullName)
            }
        }
    }
    Write-Output "$kind resources: $($catalog.Languages.Count) languages, $($baseline.Count) source strings."
}
