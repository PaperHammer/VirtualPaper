            float IdlePeriodSeconds,
            float MotionResponseSeconds,
            float IdleTransitionSeconds,
            float PointerRange,
            float MaximumMotionSpeed,
            IReadOnlyList<MotionObject> Objects);

        internal sealed record MotionObject(
            string Id,
            string Texture,
            int BackToFrontIndex,
            float Depth,
            float MotionFactor);

        internal sealed record WebProjectMetadata(
            string Title,
            string Description,
            string Authors,
            string Tags,
            string File,
            string Preview);

