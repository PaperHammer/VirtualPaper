    /// <summary>
    /// Builds a self-contained VirtualPaper web-wallpaper package. The
    /// background is warped continuously by its repaired depth texture while
    /// detected objects remain independent transparent layers.
    /// </summary>
    internal static partial class DynamicImageWebExporter {
        internal static DynamicImageWebExport Export(
            string imagePath,
            DynamicImageAnalysisResult analysis,
            string outputRoot,
            string backgroundPlatePath,
            string backgroundDepthPath,
            string diagnosticPreviewPath,
            IReadOnlyList<DynamicImageLayerExport> exports,
            CancellationToken ct) {

            ct.ThrowIfCancellationRequested();
            string webRoot = Path.Combine(outputRoot, "web");
            string assetRoot = Path.Combine(webRoot, "assets");
            string objectRoot = Path.Combine(assetRoot, "objects");
            Directory.CreateDirectory(objectRoot);

            string webBackgroundPath = Path.Combine(assetRoot, "background.png");
            string webDepthPath = Path.Combine(assetRoot, "background_depth.png");
            SaveRuntimeTexture(backgroundPlatePath, webBackgroundPath, 4096);
            SaveRuntimeTexture(backgroundDepthPath, webDepthPath, 1024);

            DynamicImageLayerPlan plan = analysis.LayerPlan;
            var exportLookup = exports.ToDictionary(item => item.LayerId, StringComparer.Ordinal);
            var objects = new List<MotionObject>();
            int objectIndex = 0;
            for (int layerIndex = 0; layerIndex < plan.Layers.Count; layerIndex++) {
                ct.ThrowIfCancellationRequested();
                DynamicImageLayer layer = plan.Layers[layerIndex];
                if (!layer.IsObject)
                    continue;

                DynamicImageLayerExport export = exportLookup[layer.Id];
                string fileName = $"object_{objectIndex:D2}.png";
                SaveRuntimeTexture(
                    export.VisibleCutoutPath,
                    Path.Combine(objectRoot, fileName),
                    4096);
                float medianDepth = Math.Clamp(layer.Depth.Median, 0f, 1f);
                objects.Add(new MotionObject(
                    layer.Id,
                    $"assets/objects/{fileName}",
                    layerIndex,
                    medianDepth,
                    0.9f + medianDepth * 0.1f));
                objectIndex++;
            }

            int safetyMargin = analysis.BackgroundPlate.SafetyMarginPixels;
            int maximumOffset = CalculateMaximumOffset(
                plan.Width,
                plan.Height,
                objects.Count,
                safetyMargin);
            var configuration = new MotionConfiguration(
                4,
                plan.Width,
                plan.Height,
                "assets/background.png",
                "assets/background_depth.png",
                safetyMargin,
                maximumOffset,
                0.15f,
                10f,
                0.3f,
                1.5f,
                0.9f,
                2.4f,
                objects);

            string motionPath = Path.Combine(webRoot, "motion.json");
            File.WriteAllText(
                motionPath,
                JsonSerializer.Serialize(
                    configuration,
                    MotionJsonContext.Default.MotionConfiguration));
            File.WriteAllText(Path.Combine(webRoot, "index.html"), IndexHtml);
            File.WriteAllText(Path.Combine(webRoot, "style.css"), StyleCss);
            File.WriteAllText(Path.Combine(webRoot, "player.js"), PlayerJavaScript);

            string previewPath = Path.Combine(assetRoot, "preview.jpg");
            SavePreview(imagePath, diagnosticPreviewPath, previewPath);
            var project = new WebProjectMetadata(
                $"{Path.GetFileNameWithoutExtension(imagePath)} - Dynamic",
                "AI layered dynamic wallpaper generated by VirtualPaper.",
                "VirtualPaper",
                "dynamic;ai;depth;parallax",
                "index.html",
                "assets/preview.jpg");
            File.WriteAllText(
                Path.Combine(webRoot, "project.json"),
                JsonSerializer.Serialize(project, MotionJsonContext.Default.WebProjectMetadata));

            ct.ThrowIfCancellationRequested();
            string packagePath = Path.Combine(outputRoot, "dynamic_wallpaper.zip");
            if (File.Exists(packagePath))
                File.Delete(packagePath);
            ZipFile.CreateFromDirectory(
                webRoot,
                packagePath,
                CompressionLevel.Optimal,
                includeBaseDirectory: false);
            return new DynamicImageWebExport(webRoot, motionPath, packagePath);
        }

        internal static int CalculateMaximumOffset(
            int width,
            int height,
            int objectCount,
            int safetyMarginPixels) {

            if (objectCount > 0 && safetyMarginPixels > 0) {
                int reserve = Math.Max(4, (int)Math.Ceiling(safetyMarginPixels * 0.125));
                return Math.Max(0, safetyMarginPixels - reserve);
            }

            return Math.Clamp(
                (int)Math.Round(Math.Min(width, height) * 0.008),
                8,
                48);
        }

        private static void SavePreview(string imagePath, string fallbackPath, string outputPath) {
            using Mat source = Cv2.ImRead(imagePath, ImreadModes.Color);
            if (source.Empty()) {
                File.Copy(fallbackPath, outputPath, overwrite: true);
                return;
            }

            const int maximumSide = 1280;
            double scale = Math.Min(1d, maximumSide / (double)Math.Max(source.Width, source.Height));
            using var preview = new Mat();
            if (scale < 1d) {
                Cv2.Resize(
                    source,
                    preview,
                    new Size(
                        Math.Max(1, (int)Math.Round(source.Width * scale)),
                        Math.Max(1, (int)Math.Round(source.Height * scale))),
                    interpolation: InterpolationFlags.Area);
            }
            else {
                source.CopyTo(preview);
            }

            if (!Cv2.ImWrite(outputPath, preview, [new ImageEncodingParam(ImwriteFlags.JpegQuality, 88)]))
                throw new IOException($"Failed to save web preview: {outputPath}");
        }

        internal static void SaveRuntimeTexture(
            string sourcePath,
            string outputPath,
            int maximumSide) {

            using Mat source = Cv2.ImRead(sourcePath, ImreadModes.Unchanged);
            if (source.Empty())
                throw new IOException($"Failed to load runtime texture: {sourcePath}");

            double scale = Math.Min(1d, maximumSide / (double)Math.Max(source.Width, source.Height));
            if (scale >= 1d) {
                File.Copy(sourcePath, outputPath, overwrite: true);
                return;
            }

            using var resized = new Mat();
            Cv2.Resize(
                source,
                resized,
                new Size(
                    Math.Max(1, (int)Math.Round(source.Width * scale)),
                    Math.Max(1, (int)Math.Round(source.Height * scale))),
                interpolation: InterpolationFlags.Area);
            if (!Cv2.ImWrite(
                outputPath,
                resized,
                [new ImageEncodingParam(ImwriteFlags.PngCompression, 4)])) {
                throw new IOException($"Failed to save runtime texture: {outputPath}");
            }
        }

        internal sealed record MotionConfiguration(
            int Version,
            int SourceWidth,
            int SourceHeight,
            string BackgroundTexture,
            string BackgroundDepthTexture,
            int SafetyMarginPixels,
            int MaximumOffsetPixels,
