        [JsonSerializable(typeof(WebProjectMetadata))]
        [JsonSourceGenerationOptions(
            PropertyNamingPolicy = JsonKnownNamingPolicy.CamelCase,
            WriteIndented = true)]
        internal sealed partial class MotionJsonContext : JsonSerializerContext;

